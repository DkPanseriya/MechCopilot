"""Regenerate docs/CALCULATORS.md from the calculator registry.

Run from the repo root:  .venv/bin/python backend/scripts/gen_docs.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "backend"))

from engineering.registry import ordered  # noqa: E402


def main() -> None:
    calcs = ordered()
    lines = [
        "# Calculator reference",
        "",
        f"MechPartner ships {len(calcs)} calculators. Each one shows an annotated diagram, live inputs "
        "with unit switching, pass/warn/fail checks, plots and the full worked solution. Open them from "
        "the **Calculator Library** or let the copilot choose them for you.",
        "",
        "_This file is generated by `backend/scripts/gen_docs.py`._",
        "",
    ]
    category = None
    for c in calcs:
        if c.category != category:
            category = c.category
            lines += [f"## {category}", ""]
        lines.append(f"### {c.title}")
        lines.append(f"`{c.id}` — {c.summary}")
        lines.append("")
        inputs = ", ".join(p.label for p in c.params if not p.advanced)
        if inputs:
            lines.append(f"- **Inputs:** {inputs}")
        primary = ", ".join(o.label for o in c.outputs if o.primary)
        if primary:
            lines.append(f"- **Key results:** {primary}")
        if c.references:
            lines.append(f"- **References:** {'; '.join(c.references)}")
        lines.append("")
    out = os.path.join(ROOT, "docs", "CALCULATORS.md")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {out} ({len(calcs)} calculators)")


if __name__ == "__main__":
    main()
