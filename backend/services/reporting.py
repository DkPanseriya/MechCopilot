import datetime
from typing import Any, Dict, List


def _fmt_input(v: Any) -> str:
    if isinstance(v, dict) and "value" in v:
        return f"{v['value']} {v.get('unit', '')}".strip()
    return str(v)


SOURCE_LABEL = {"user": "given", "assumed": "assumed", "derived": "derived"}


def _source(meta: Dict[str, Any]) -> str:
    label = SOURCE_LABEL.get(meta.get("source"), "")
    return f"{label}: {meta['why']}" if label and meta.get("why") else label


def _calc_sections(tool_data: Dict[str, Any]) -> List[str]:
    md: List[str] = []
    # Results are stored in the same order as the tools (one calculator may run twice).
    results = tool_data.get("results", [])
    for i, tool in enumerate(tool_data.get("tools", [])):
        if tool.get("type") != "calc":
            continue
        md.append(f"### {tool.get('title', tool.get('calculator'))}")
        if tool.get("purpose"):
            md.append(f"_{tool['purpose']}_")
        if tool.get("example"):
            md.append("\n> Example: run on the calculator's default values to illustrate, not a design check.")
        if tool.get("provisional"):
            md.append(f"\n> Provisional: calculator defaults used for {', '.join(f'`{n}`' for n in tool['provisional'])}"
                      " — confirm these before relying on the result.")
        prov = tool.get("provenance") or {}
        if tool.get("inputs"):
            md.append("")
            md.append("| Input | Value | Source |")
            md.append("| :--- | :--- | :--- |")
            for k, v in tool["inputs"].items():
                md.append(f"| `{k}` | {_fmt_input(v)} | {_source(prov.get(k, {}))} |")
        defaults = [k for k, meta in prov.items() if meta.get("source") == "default"]
        if defaults:
            md.append(f"\nCalculator defaults used for: {', '.join(f'`{k}`' for k in defaults)}.")
        res = results[i] if i < len(results) else None
        if res and "error" in res:
            md.append(f"\n> Calculation error: {res['error']}")
        elif res:
            md.append("")
            md.append("| Result | Value |")
            md.append("| :--- | :--- |")
            for label, value in res.get("outputs", {}).items():
                md.append(f"| {label} | {value} |")
            if res.get("checks"):
                md.append("")
                md.append("**Checks**")
                for c in res["checks"]:
                    md.append(f"- {c}")
            for link in res.get("links", []):
                md.append(f"- {link}")
        md.append("")
    if tool_data.get("assumptions"):
        md.append("**Assumptions**")
        md.extend(f"- {a}" for a in tool_data["assumptions"])
        md.append("")
    return md


def generate_markdown_report(session_title: str, messages: List[Dict[str, Any]]) -> str:
    """Markdown engineering report for a chat session, including computed results."""
    date_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    md = [
        "# Engineering Design Report",
        f"**Session:** {session_title}  ",
        f"**Date:** {date_str}  ",
        "**Generated by:** MechCopilot",
        "",
        "---",
        "",
    ]

    for msg in messages:
        role = msg.get("role")
        content = msg.get("content") or ""
        tool_data = msg.get("tool_data") or {}

        if role == "user":
            md.append("## Request")
            md.append(f"> {content}")
            md.append("")
        elif role == "assistant":
            md.append("## Analysis")
            if content:
                md.append(content)
                md.append("")
            if isinstance(tool_data, dict) and tool_data.get("tools"):
                md.extend(_calc_sections(tool_data))
            elif isinstance(tool_data, dict) and (tool_data.get("steps") or tool_data.get("tool_name")):
                title = tool_data.get("workflow_name") or tool_data.get("tool_name", "Calculation")
                md.append(f"### {title}")
                for step in tool_data.get("steps", []):
                    md.append(f"- Step {step.get('step_id', '?')}: `{step.get('relation', '?')}` — "
                              f"{step.get('explanation', '')}")
                md.append("")

    md.append("---")
    md.append("*Calculations by MechCopilot. All results must be verified by a qualified engineer "
              "before manufacture or use.*")
    return "\n".join(md)
