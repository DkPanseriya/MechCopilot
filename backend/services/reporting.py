import datetime
from typing import List, Dict, Any

def generate_markdown_report(session_title: str, messages: List[Dict[str, Any]]) -> str:
    """
    Generates a professional Markdown report from a chat session.
    """
    date_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    md = [
        f"# Engineering Design Report",
        f"**Project/Session:** {session_title}",
        f"**Date:** {date_str}",
        f"**Generated By:** Mech Copilot v2",
        "---",
        ""
    ]
    
    for msg in messages:
        role = msg.get("role")
        content = msg.get("content", "")
        tool_data = msg.get("tool_data")
        
        if role == "user":
            md.append(f"## Request")
            md.append(f"> {content}")
            md.append("")
            
        elif role == "assistant":
            md.append(f"## Analysis")
            
            # If there's direct text content
            if content:
                md.append(content)
                md.append("")
            
            # If there's a tool/workflow execution
            if tool_data:
                tool_name = tool_data.get("tool_name", "Calculation")
                workflow_name = tool_data.get("workflow_name")
                
                title = workflow_name if workflow_name else tool_name
                md.append(f"### Executed Workflow: {title}")
                
                # Format Workflow Steps
                steps = tool_data.get("steps", [])
                if steps:
                    md.append("| Step | Relation | Explanation | Result |")
                    md.append("| :--- | :--- | :--- | :--- |")
                    
                    # We might not have the *results* joined here easily unless we passed them in 
                    # or if they are embedded. The current architecture stores messages. 
                    # The Frontend renders results from a separate state usually? 
                    # Wait, the backend stores messages. Does it store the RESULTS of the tools?
                    # Currently, the Agent output contains the TOOL CALL (JSON). 
                    # It does NOT strictly contain the runtime results unless we saved them back to DB.
                    # Looking at `database.py`/`sessions.py`, we store `tool_call` JSON.
                    # We do NOT seem to store the "Result" JSON permanently in the message history in a standard way yet.
                    # For V1 of reporting, we will document the *Proposed Pathway* (The Workflow Plan).
                    
                    for step in steps:
                        s_id = step.get("step_id", "?")
                        rel = step.get("relation", "?")
                        expl = step.get("explanation", "-")
                        # inputs = step.get("inputs", {})
                        
                        md.append(f"| {s_id} | `{rel}` | {expl} | *Executed* |")
                    
                    md.append("")
                    md.append("> **Note**: Check system logs for precise numerical outputs if not explicitly stated in text.")
                    md.append("")
                
    md.append("---")
    md.append("**End of Report**")
    md.append("*Verified by Artificial Intelligence. Engineering review required before manufacturing.*")
    
    return "\n".join(md)
