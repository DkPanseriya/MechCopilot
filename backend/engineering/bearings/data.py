def _speeds(t: str, d: float, D: float):
    a_ref, a_lim = _SPEED_A[t]
    dm = (d + D) / 2
    r = lambda v: int(round(v / dm / 100.0) * 100)
    return r(a_ref), r(a_lim)


def _skf_suffix(t: str, base: str, d: float) -> str:
    """Typical SKF full designation for a base designation (verify availability)."""
    if t == "acbb":
        return f"{base}CBP" if d <= 60 else f"{base}CBM"
    if t == "crb":
        return f"{base} ECP"
    if t == "trb":
        return f"{base} J2" if d <= 20 else f"{base} J2/Q"
    if t == "sabb":
        return f"{base} ETN9" if d <= 60 else base
    if t == "srb":
        return f"{base} E"
    return base


def _row(t, series, base, d, D, B, C, C0, Pu, n_ref=None, n_lim=None, **extra) -> Dict[str, Any]:
    if n_ref is None:
        n_ref, n_lim = _speeds(t, d, D)
    row = {
        "base": base, "type": t, "series": series, "d": float(d), "D": float(D), "B": float(B),
        "C": C * 1000.0, "C0": C0 * 1000.0, "Pu": Pu * 1000.0,
        "n_ref": float(n_ref), "n_lim": float(n_lim),
        "skf": _skf_suffix(t, base, d), "source": "typical",
        "e": None, "Y": None, "Y0": None, "Y1": None, "Y2": None, "f0": None,
    }
    row.update(extra)
    return row


def _build() -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for s, items in _DGBB.items():
        for (base, d, D, B, C, C0, Pu, nr, nl) in items:
            rows.append(_row("dgbb", s, base, d, D, B, C, C0, Pu, nr, nl, f0=_F0[s]))
    for s, items in _ACBB.items():
        for (base, d, D, B, C, C0, Pu) in items:
            rows.append(_row("acbb", s, base, d, D, B, C, C0, Pu))
    for s, items in _CRB.items():
        for (base, d, D, B, C, C0, Pu) in items:
            rows.append(_row("crb", s, base, d, D, B, C, C0, Pu))
    for s, items in _TRB.items():
        for (base, d, D, T, C, C0, Pu, e, Y, Y0) in items:
            rows.append(_row("trb", s, base, d, D, T, C, C0, Pu, e=e, Y=Y, Y0=Y0))
    for s, items in _SABB.items():
        for (base, d, D, B, C, C0, Pu, e, Y1, Y2, Y0) in items:
            rows.append(_row("sabb", s, base, d, D, B, C, C0, Pu, e=e, Y1=Y1, Y2=Y2, Y0=Y0))
    for s, items in _SRB.items():
        for (base, d, D, B, C, C0, Pu, e, Y1, Y2, Y0) in items:
            rows.append(_row("srb", s, base, d, D, B, C, C0, Pu, e=e, Y1=Y1, Y2=Y2, Y0=Y0))
    for s, items in _TBB.items():
        for (base, d, D, H, C, C0, Pu) in items:
            rows.append(_row("tbb", s, base, d, D, H, C, C0, Pu))
    return rows


