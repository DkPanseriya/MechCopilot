def variant_designation(b: Dict[str, Any], seal: str = "open") -> str:
    """SKF-style designation incl. seal/shield suffix (deep groove only)."""
    if b["type"] == "dgbb" and b["source"] != "user":
        if seal == "2z":
            return f"{b['base']}-2Z"
        if seal == "2rsh":
            return f"{b['base']}-2RSH"
    return b["skf"]


def skf_links(b: Dict[str, Any], seal: str = "open") -> List[Dict[str, str]]:
    links = []
    full = variant_designation(b, seal)
    if b["type"] == "dgbb" and b["source"] != "user":
        links.append({"label": f"SKF {b['base']} page", "url": SKF_DGBB_PAGE.format(q=quote(b["base"]))})
    links.append({"label": f"Search {full} on SKF", "url": SKF_SEARCH.format(q=quote(full))})
    return links


def limiting_speed(b: Dict[str, Any], seal: str = "open") -> float:
    """Contact seals (2RSH) roughly halve the limiting speed of a deep groove bearing."""
    if b["type"] == "dgbb" and seal == "2rsh":
        return round(b["n_lim"] * 0.42, -2)
    return b["n_lim"]


def get(base: Optional[str]) -> Optional[Dict[str, Any]]:
    return BY_BASE.get(base) if base else None
