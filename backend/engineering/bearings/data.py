REQUIRED_COLUMNS = ["designation", "type", "d", "D", "B", "C", "C0", "Pu", "n_ref", "n_lim"]
OPTIONAL_COLUMNS = ["e", "Y", "Y0", "Y1", "Y2", "f0"]


def parse_user_row(raw: Dict[str, str]) -> Dict[str, Any]:
    """Convert one validated CSV row (loads in kN, dims in mm, speeds rpm) to a DB row."""
    t = raw["type"].strip().lower()
    num = lambda k: float(raw[k])
    opt = lambda k: float(raw[k]) if raw.get(k) not in (None, "") else None
    row = _row(t, "user", raw["designation"].strip(), num("d"), num("D"), num("B"),
               num("C"), num("C0"), num("Pu"), num("n_ref"), num("n_lim"),
               **{k: opt(k) for k in OPTIONAL_COLUMNS})
    row["skf"] = raw["designation"].strip()
    row["source"] = "user"
    if t == "dgbb" and row["f0"] is None:
        row["f0"] = 13.5
    return row


def load_user_rows(path: str = USER_FILE) -> List[Dict[str, Any]]:
    if not os.path.isfile(path):
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return [parse_user_row(r) for r in csv.DictReader(f)]


def _merge(base_rows: List[Dict[str, Any]], user_rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    by_key = {r["base"]: r for r in base_rows}
    for u in user_rows:
        by_key[u["base"]] = u
    return list(by_key.values())


def _safe_user_rows() -> List[Dict[str, Any]]:
    try:
        return load_user_rows()
    except Exception as e:  # a broken user file must never take the app down
        print(f"WARNING: ignoring user bearing file {USER_FILE}: {e}")
        return []


BEARINGS: List[Dict[str, Any]] = _merge(_build(), _safe_user_rows())
BY_BASE: Dict[str, Dict[str, Any]] = {b["base"]: b for b in BEARINGS}


def by_type(t: str) -> List[Dict[str, Any]]:
    return sorted([b for b in BEARINGS if b["type"] == t], key=lambda b: (b["series"], b["d"], b["D"]))


def designation_options(t: str) -> List[Dict[str, str]]:
    return [{"value": b["base"], "label": f"{b['skf']}  ({fmt_env(b)})"} for b in by_type(t)]


def fmt_env(b: Dict[str, Any]) -> str:
    g = lambda v: f"{v:g}"
    return f"{g(b['d'])}×{g(b['D'])}×{g(b['B'])} mm"


